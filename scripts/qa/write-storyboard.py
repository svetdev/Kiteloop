#!/usr/bin/env python3
"""Turn the screenshots a QA flow attached into its storyboard.

    write-storyboard.py <exported attachments dir> <storyboards dir> <item id> <test class>

`xcresulttool export attachments` leaves the files and a manifest.json; each
step's attachment is named "NN caption" by QAStoryboardTestCase.step. This
copies them, in step order, to <storyboards>/<id>/ and writes <storyboards>/<id>.md
— one heading and picture per step — which is what the QA agent opens.
"""
import json
import re
import shutil
import sys
from pathlib import Path


def parse_step(name: str):
    """(number, caption) from an attachment's exported name, or None.

    xcresulttool appends "_<n>_<UUID>" before what it takes for an extension —
    ".png", or the tail of a caption that held a dot."""
    match = re.match(r"(\d+) (.*?)(?:_\d+_[0-9A-F]{8}(?:-[0-9A-F]{4}){3}-[0-9A-F]{12}(\.[^.]*)?)?$", name)
    if not match:
        return None
    tail = match.group(3) or ""
    return int(match.group(1)), match.group(2) + ("" if tail == ".png" else tail)


def steps(shots: Path, test_class: str):
    manifest = json.loads((shots / "manifest.json").read_text())
    found = []
    for test in manifest:
        if test_class not in str(test.get("testIdentifier", "")):
            continue
        for item in test.get("attachments", []):
            name = item.get("suggestedHumanReadableName") or item.get("name") or ""
            step = parse_step(name)
            if step:
                found.append((*step, shots / item["exportedFileName"]))
    return sorted(found)


def main(shots: str, boards: str, item_id: str, test_class: str) -> int:
    shots_dir, boards_dir = Path(shots), Path(boards)
    pictures = boards_dir / item_id
    shutil.rmtree(pictures, ignore_errors=True)
    pictures.mkdir(parents=True)
    lines = [f"# {item_id}", "", f"Generated by scripts/qa/run-ui-flow.sh from {test_class}. "
             "Each step is the app's window once the step was done.", ""]
    found = steps(shots_dir, test_class)
    for number, caption, source in found:
        slug = re.sub(r"[^a-z0-9]+", "-", caption.lower()).strip("-")[:60]
        target = pictures / f"{number:02d}-{slug}.png"
        shutil.copyfile(source, target)
        lines += [f"## {number}. {caption}", "", f"![{caption}]({item_id}/{target.name})", ""]
    (boards_dir / f"{item_id}.md").write_text("\n".join(lines))
    print(f"  {boards_dir / (item_id + '.md')} — {len(found)} step(s)")
    return 0 if found else 1


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:5]))
