import XCTest
@testable import KiteloopCore

/// Finding the storyboard an item's QA run kept, and reading its steps back for
/// whoever approves the item.
final class QAStoryboardPageTests: XCTestCase {

    @discardableResult
    private func keepPage(home: URL, itemID: String, runID: String, modified: Date = Date(),
                          page: String = "# page\n") throws -> URL {
        let run = QAStoryboardArchive.destination(home: home, itemID: itemID, runID: runID)
        try FileManager.default.createDirectory(at: run, withIntermediateDirectories: true)
        let url = run.appending(path: "\(itemID).md")
        try Data(page.utf8).write(to: url)
        try FileManager.default.setAttributes([.modificationDate: modified], ofItemAtPath: url.path(percentEncoded: false))
        return url
    }

    func testTheNewestRunsPageIsFoundWhateverTheRunsAreNamed() throws {
        let home = try makeTemporaryDirectory()
        let now = Date()
        // Name order and date order disagree: "run-b" sorts after "run-a" but is older.
        try keepPage(home: home, itemID: "qa-demo", runID: "run-b", modified: now)
        let newest = try keepPage(home: home, itemID: "qa-demo", runID: "run-a", modified: now.addingTimeInterval(60))

        let found = try XCTUnwrap(QAStoryboardPage.latest(home: home, itemID: "qa-demo"))

        XCTAssertEqual(found.standardizedFileURL, newest.standardizedFileURL)
    }

    func testNoStoryboardFolderFindsNone() throws {
        XCTAssertNil(QAStoryboardPage.latest(home: try makeTemporaryDirectory(), itemID: "qa-demo"))
    }

    func testRunFoldersWithoutAPageFindNone() throws {
        let home = try makeTemporaryDirectory()
        let run = QAStoryboardArchive.destination(home: home, itemID: "qa-demo", runID: "run-1")
        try FileManager.default.createDirectory(at: run.appending(path: "qa-demo"), withIntermediateDirectories: true)
        try Data([0x89]).write(to: run.appending(path: "qa-demo/01-shot.png"))
        // Neither a stray file beside where the page would be, nor a folder
        // that only looks like a page, is one.
        try Data([0x89]).write(to: run.appending(path: "stray.png"))
        try FileManager.default.createDirectory(at: run.appending(path: "notes.md"), withIntermediateDirectories: true)
        try FileManager.default.createDirectory(
            at: QAStoryboardArchive.destination(home: home, itemID: "qa-demo", runID: "run-2"),
            withIntermediateDirectories: true)

        XCTAssertNil(QAStoryboardPage.latest(home: home, itemID: "qa-demo"))
    }

    func testAnotherItemsStoryboardIsNotThisOnes() throws {
        let home = try makeTemporaryDirectory()
        try keepPage(home: home, itemID: "other", runID: "run-1")

        XCTAssertNil(QAStoryboardPage.latest(home: home, itemID: "qa-demo"))
    }

    func testStepsAreReadInPageOrderWithTheirPictures() throws {
        let home = try makeTemporaryDirectory()
        let url = try keepPage(home: home, itemID: "qa-demo", runID: "run-1", page: """
        # qa-demo

        Generated by scripts/qa/run-ui-flow.sh.

        ## 1. The Autopilot view opens

        ![The Autopilot view opens](qa-demo/01-the-autopilot-view-opens.png)

        ## 2. The row shows a branch

        ![The row shows a branch](qa-demo/02-the-row-shows-a-branch.png)

        ## 3. FAILED: The button is blue — got grey

        ![FAILED: The button is blue — got grey](qa-demo/03-failed-the-button-is-blue-got-grey.png)

        """)
        let pictures = url.deletingLastPathComponent().appending(path: "qa-demo")
        try FileManager.default.createDirectory(at: pictures, withIntermediateDirectories: true)
        for name in ["01-the-autopilot-view-opens.png", "03-failed-the-button-is-blue-got-grey.png"] {
            try Data([0x89]).write(to: pictures.appending(path: name))
        }

        let page = try XCTUnwrap(QAStoryboardPage.read(url))

        XCTAssertEqual(page.steps.map(\.number), [1, 2, 3])
        XCTAssertEqual(page.steps.map(\.caption), ["The Autopilot view opens", "The row shows a branch",
                                                   "FAILED: The button is blue — got grey"])
        XCTAssertEqual(page.steps.map(\.failed), [false, false, true])
        XCTAssertEqual(page.steps[0].picture?.standardizedFileURL,
                       pictures.appending(path: "01-the-autopilot-view-opens.png").standardizedFileURL)
        XCTAssertNil(page.steps[1].picture, "a picture missing on disk is reported missing")
        XCTAssertNotNil(page.steps[2].picture)
    }

    func testAStepWithNoPictureLineIsStillAStep() throws {
        let url = try keepPage(home: try makeTemporaryDirectory(), itemID: "qa-demo", runID: "run-1",
                               page: "## 1. First\n\n## 2. Second\n")

        let page = try XCTUnwrap(QAStoryboardPage.read(url))

        XCTAssertEqual(page.steps.map(\.caption), ["First", "Second"])
        XCTAssertEqual(page.steps.map(\.picture), [nil, nil])
    }

    func testAPictureUnderAHomeWithASpaceInItsPathIsFound() throws {
        let home = try makeTemporaryDirectory().appending(path: "Application Support", directoryHint: .isDirectory)
        let url = try keepPage(home: home, itemID: "qa-demo", runID: "run-1",
                               page: "## 1. First\n\n![First](qa-demo/01-first.png)\n")
        let pictures = url.deletingLastPathComponent().appending(path: "qa-demo")
        try FileManager.default.createDirectory(at: pictures, withIntermediateDirectories: true)
        try Data([0x89]).write(to: pictures.appending(path: "01-first.png"))

        let page = try XCTUnwrap(QAStoryboardPage.read(url))

        XCTAssertNotNil(page.steps.first?.picture, "a space in the home's path must not lose the picture")
    }

    func testAMissingPageReadsAsNone() throws {
        XCTAssertNil(QAStoryboardPage.read(try makeTemporaryDirectory().appending(path: "gone.md")))
    }
}
